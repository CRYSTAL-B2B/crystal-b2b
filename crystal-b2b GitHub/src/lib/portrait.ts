import { existsSync } from "node:fs";
import path from "node:path";

/**
 * Фотография в блоке опыта.
 *
 * Файла в репозитории пока нет, и выдумывать нечего: портрет либо есть, либо
 * блока с ним нет. Наличие проверяется на сборке - экспорт статический, все
 * серверные компоненты выполняются один раз в момент build. Владельцу
 * достаточно положить файл по этому пути и пересобрать: разметка, стили и
 * поле image в разметке Person появятся сами, править код не понадобится.
 *
 * Размеры заданы явно и должны совпадать с реальными - иначе при загрузке
 * страница дёрнется. Если пропорции портрета окажутся другими, поправить
 * width и height здесь.
 *
 * Модуль читает файловую систему, поэтому импортировать его можно только из
 * серверных компонентов.
 */
export const portrait = {
  src: "/media/photo/daniil-chekulaev.webp",
  width: 800,
  height: 1000,
  alt: "Даниил Чекулаев",
} as const;

export function hasPortrait(): boolean {
  return existsSync(path.join(process.cwd(), "public", portrait.src));
}
